// Every other Danube project on danubeproperties.com, as published on its own
// project page (fetched October 2026). Bayz 102, Shahrukhz Residences and
// Greenz are hand-built in lib/inventory.ts because they carry more detail.
//
// Only what a page states is recorded here. "from" is the starting price the
// listing or FAQ gives, in AED. A page that tags its price "SOLD OUT" is marked
// `sold`, and a completed project is sold out too, so neither gets bookable
// units. Where a page contradicts itself (two handover dates, two prices) the
// first value is used and the conflict is kept in `notes` for the advisor.

export type ProjectStatus = "latest_launch" | "ongoing" | "completed";

export interface ProjectSpec {
  id: string;
  name: string;
  /** Area, as the page gives it. */
  area: string;
  status: ProjectStatus;
  /** The listing tags the price "SOLD OUT", or the project is completed and sold. */
  sold?: boolean;
  handover?: string;
  /** Payment plan exactly as the page labels it. */
  plan?: string;
  /** Starting price in AED. */
  from?: number;
  /** Published prices by bedroom count (0 = studio), in AED. */
  typePrices?: Record<number, number>;
  /** Layouts as the page lists them, for display. */
  types: string[];
  /** Bedroom counts to generate sample units for (bookable projects only). */
  beds?: number[];
  /** Total units in the project, as stated. */
  units?: number;
  floors?: number;
  furnished?: boolean;
  amenities: string[];
  /** Nearby places and the minutes the page gives. */
  nearby: [string, number][];
  image: string;
  /** Conflicts and extra facts the advisor should know. */
  notes?: string[];
  /** Two letters, unique across bookable projects. */
  prefix?: string;
  /** An office tower rather than homes. */
  office?: boolean;
}

